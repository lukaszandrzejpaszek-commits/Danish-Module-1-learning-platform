const originalText = new WeakMap();
const originalAttributes = new WeakMap();

export function translateUiText(text) {
  const value = String(text ?? "");
  if (currentLanguage !== "da") return value;
  if (ENGLISH_TO_DANISH[value]) return ENGLISH_TO_DANISH[value];
  for (const [pattern, translate] of PATTERNS) {
    const match = value.match(pattern);
    if (match) return translate(...match.slice(1));
  }
  return value;
}

export function setUiText(element, englishText) {
  const value = String(englishText ?? "");
  element.textContent = value;
  if (element.firstChild) {
    originalText.set(element.firstChild, value);
    element.firstChild.nodeValue = translateUiText(value);
  }
}

export function setUiAttribute(element, name, englishValue) {
  let attributes = originalAttributes.get(element);
  if (!attributes) {
    attributes = new Map();
    originalAttributes.set(element, attributes);
  }
  attributes.set(name, String(englishValue));
  element.setAttribute(name, translateUiText(englishValue));
}

export function setInterfaceLanguage(language) {
  currentLanguage = language === "da" ? "da" : "en";
  document.documentElement.lang = currentLanguage;

  const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement && node.parentElement.closest("[data-no-translate]")) continue;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const value = originalText.get(node);
    const content = value.trim();
    if (!content) {
      node.nodeValue = value;
      continue;
    }
    const leading = value.match(/^\s*/)?.[0] || "";
    const trailing = value.match(/\s*$/)?.[0] || "";
    node.nodeValue = `${leading}${translateUiText(content)}${trailing}`;
  }

  document.querySelectorAll("[placeholder], [aria-label], [title], [alt]").forEach((element) => {
    let attributes = originalAttributes.get(element);
    if (!attributes) {
      attributes = new Map();
      originalAttributes.set(element, attributes);
    }
    ["placeholder", "aria-label", "title", "alt"].forEach((name) => {
      if (!element.hasAttribute(name)) return;
      if (!attributes.has(name)) attributes.set(name, element.getAttribute(name));
      element.setAttribute(name, translateUiText(attributes.get(name)));
    });
  });

  document.querySelectorAll(".language-btn").forEach((button) => {
    const selected = button.dataset.language === currentLanguage;
    button.classList.toggle("active", selected);
    button.setAttribute("aria-pressed", String(selected));
  });
}
